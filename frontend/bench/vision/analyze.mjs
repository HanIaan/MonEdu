#!/usr/bin/env node
/**
 * Turns .cache/results/raw.json (from run.mjs) into the comparison tables in .cache/results/tables.md.
 * Every number in RESULTS.md comes from this script's output. Behaviour latency uses the REAL state
 * machine (harness/sim.ts → src/features/monitoring/engine/stateMachine.ts).
 * Usage: node analyze.mjs [raw.json]
 */
import { build } from 'rolldown';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(HERE, '..', '..');
const RES_DIR = join(HERE, '.cache', 'results');
const rawPath = process.argv[2] ?? join(RES_DIR, 'raw.json');
const raw = JSON.parse(readFileSync(rawPath, 'utf8'));
const { entries } = JSON.parse(readFileSync(join(HERE, 'manifest.json'), 'utf8'));

// Bundles go outside the repo tree so `eslint .` never sees generated code.
const BUILD = process.env.BENCH_BUILD_DIR ?? join(tmpdir(), 'study-monitor-vision-bench');
mkdirSync(BUILD, { recursive: true });
await build({
  input: join(HERE, 'harness', 'sim.ts'),
  resolve: { alias: { '@': join(FRONTEND, 'src') } },
  output: { file: join(BUILD, 'sim.mjs'), format: 'esm' },
  logLevel: 'warn',
});
const sim = await import(pathToFileURL(join(BUILD, 'sim.mjs')).href);

const byFile = new Map(raw.results.map((r) => [r.image.replace('/images/', ''), r]));
const subset = (name) => entries.filter((e) => e.subset === name).map((e) => ({ e, r: byFile.get(e.file) })).filter((x) => x.r && !x.r.error);

const mean = (a) => (a.length ? a.reduce((s, v) => s + v, 0) / a.length : NaN);
const pct = (a, p) => {
  if (!a.length) return NaN;
  const s = [...a].sort((x, y) => x - y);
  return s[Math.min(s.length - 1, Math.ceil((p / 100) * s.length) - 1)];
};
const f1 = (v) => (Number.isFinite(v) ? v.toFixed(1) : '–');
const f2 = (v) => (Number.isFinite(v) ? v.toFixed(2) : '–');
const f3 = (v) => (Number.isFinite(v) ? v.toFixed(3) : '–');

const pos = subset('phone_pos');
const neg = subset('phone_neg');
const out = [];
out.push(`# Benchmark tables (generated by analyze.mjs)\n`);
out.push(`run: ${raw.meta.date} · ${raw.meta.userAgent} · ${raw.meta.platform} · model load ${f1(raw.meta.loadMs)} ms · wall ${f1(raw.meta.wallS)} s\n`);
out.push(`phone_pos n=${pos.length}, phone_neg n=${neg.length} (hard negatives: ${neg.filter((x) => x.e.gt.hardNegative).length})\n`);

// ───────────── A: phone options ─────────────
const T = 0.5;
/** Option = name + per-image phone score getter + per-tick detector cost getter + per-tick face/pose resolution. */
const det = (res, key) => (r) => r.res[res]?.det[key];
const roi = (res, key) => (r) => r.res[res]?.roi[key] ?? r.res[res]?.det[key]; // no pose → full frame fallback
const OPTIONS = [
  { name: '(1) 320×240 · Lite0 int8 (current)', get: det('320', 'lite0_int8'), fp: '320' },
  { name: '(2) 640×480 · Lite0 int8', get: det('640', 'lite0_int8'), fp: '640' },
  { name: '(3) split: face/pose 320 + Lite0 int8 @640', get: det('640', 'lite0_int8'), fp: '320', resizeMs: true },
  { name: '(4a) 320 · Lite0 float16', get: det('320', 'lite0_f16'), fp: '320' },
  { name: '(4b) 640 · Lite0 float16', get: det('640', 'lite0_f16'), fp: '640' },
  { name: '(4c) 320 · Lite2 int8', get: det('320', 'lite2_int8'), fp: '320' },
  { name: '(4d) 640 · Lite2 int8', get: det('640', 'lite2_int8'), fp: '640' },
  { name: '(4e) 320 · SSD-MobileNetV2 f32', get: det('320', 'ssd_mnv2_f32'), fp: '320' },
  { name: '(4f) 640 · SSD-MobileNetV2 f32', get: det('640', 'ssd_mnv2_f32'), fp: '640' },
  { name: '(5a) 320 · ROI(upper body) Lite0 int8', get: roi('320', 'lite0_int8'), fp: '320', roi: true },
  { name: '(5b) 640 · ROI(upper body) Lite0 int8', get: roi('640', 'lite0_int8'), fp: '640', roi: true },
  { name: '(5c) split 320 + ROI@640 Lite0 int8', get: roi('640', 'lite0_int8'), fp: '320', roi: true, resizeMs: true },
  { name: '(5d) 640 · ROI Lite2 int8', get: roi('640', 'lite2_int8'), fp: '640', roi: true },
];

function confusion(get, thr) {
  let tp = 0, fn = 0, fp = 0, tn = 0;
  for (const { r } of pos) {
    if ((get(r)?.phone ?? 0) >= thr) tp++;
    else fn++;
  }
  for (const { r } of neg) {
    if ((get(r)?.phone ?? 0) >= thr) fp++;
    else tn++;
  }
  return { tp, fn, fp, tn, p: tp / (tp + fp), rc: tp / (tp + fn) };
}

const all = [...pos, ...neg];
out.push(`\n## A. Phone: per-image detection at phoneMinScore = ${T} (unchanged)\n`);
out.push('Cost columns are per tick on the main thread, all images of phone_pos ∪ phone_neg. CPU ms/s = face+pose ms × 2 (500 ms cadence) + detector ms × 1 (1000 ms cadence) [+ crop/resize].\n');
out.push('| Option | P | R | TP | FP | FN | TN | det mean ms | det p95 ms | face+pose mean ms | CPU ms/s |');
out.push('|---|---|---|---|---|---|---|---|---|---|---|');
const optSummary = [];
for (const o of OPTIONS) {
  const c = confusion(o.get, T);
  const dms = all.map(({ r }) => (o.get(r)?.ms ?? NaN) + (o.roi ? (o.get(r)?.cropMs ?? 0) : 0)).filter(Number.isFinite);
  const fpms = all.map(({ r }) => r.res[o.fp].faceMs + r.res[o.fp].poseMs);
  // ESTIMATE-free resize cost: split mode needs a 640→320 downscale for face/pose; measured separately in mem/latency probe.
  const cpu = mean(fpms) * 2 + mean(dms);
  optSummary.push({ name: o.name, ...c, detMean: mean(dms), detP95: pct(dms, 95), fpMean: mean(fpms), cpu });
  out.push(`| ${o.name} | ${f2(c.p)} | ${f2(c.rc)} | ${c.tp} | ${c.fp} | ${c.fn} | ${c.tn} | ${f1(mean(dms))} | ${f1(pct(dms, 95))} | ${f1(mean(fpms))} | ${f1(cpu)}${o.resizeMs ? ' +resize' : ''} |`);
}

out.push(`\n### Threshold sensitivity (for context only — the default stays ${T})\n`);
out.push('| Option | R@0.3 (P) | R@0.4 (P) | R@0.5 (P) | R@0.6 (P) |');
out.push('|---|---|---|---|---|');
for (const o of OPTIONS) {
  const cells = [0.3, 0.4, 0.5, 0.6].map((t) => {
    const c = confusion(o.get, t);
    return `${f2(c.rc)} (${f2(c.p)})`;
  });
  out.push(`| ${o.name} | ${cells.join(' | ')} |`);
}

out.push(`\n### Recall by phone size (share of image area, COCO box) at ${T}\n`);
const buckets = [
  ['< 0.5 %', (a) => a < 0.005],
  ['0.5–2 %', (a) => a >= 0.005 && a < 0.02],
  ['≥ 2 %', (a) => a >= 0.02],
];
out.push(`| Option | ${buckets.map(([n]) => `${n} (n=${pos.filter((x) => buckets.find((b) => b[0] === n)[1](x.e.gt.maxPhoneArea)).length})`).join(' | ')} |`);
out.push(`|---|${buckets.map(() => '---').join('|')}|`);
for (const o of OPTIONS) {
  const cells = buckets.map(([, f]) => {
    const s = pos.filter((x) => f(x.e.gt.maxPhoneArea));
    return f2(s.filter(({ r }) => (o.get(r)?.phone ?? 0) >= T).length / s.length);
  });
  out.push(`| ${o.name} | ${cells.join(' | ')} |`);
}

out.push(`\n### Hard negatives (remote/laptop/keyboard/book/mouse present, no phone) FP at ${T}\n`);
for (const o of OPTIONS.slice(0, 3).concat(OPTIONS.filter((x) => x.roi))) {
  const h = neg.filter((x) => x.e.gt.hardNegative);
  out.push(`- ${o.name}: ${h.filter(({ r }) => (o.get(r)?.phone ?? 0) >= T).length}/${h.length}`);
}

// ───────────── A6: temporal smoothing / behaviour latency ─────────────
out.push(`\n## A6. Temporal behaviour (simulation with the real state machine)\n`);
out.push('Each phone_pos / phone_neg image has 8 camera-like perturbations (crop 90–100 %, shift, brightness ±15 %, 30 % 1 px blur) scored by the detector. A seated student is simulated (FOCUS_ESTIMATED), then the phone "appears" at t=0 and stays for 60 s; at every phone evaluation one of the 8 measured scores is drawn at random (5 seeds per image). Latency = t(DISTRACTION_SUSPECTED) − t(phone appears). For phone_neg images the same procedure gives the false-suspicion rate per 60 s of phone-free studying. LIMIT: draws are independent; real consecutive frames are correlated (a hidden phone stays hidden), so real-world recall is lower than this for "sometimes detected" phones.\n');
out.push('| Config | rule | cadence (face/pose, phone) | per-frame det. rate pos | suspected within 60 s (pos) | latency median s | latency p95 s | false suspicion / 60 s (neg) |');
out.push('|---|---|---|---|---|---|---|---|');
const jkeys = Object.keys(pos.find((x) => x.r.jitter)?.r.jitter ?? {});
const RULES = [
  { name: 'state machine (20 s + 3 s debounce)', kOfN: undefined },
  { name: '+ 2-of-3 pre-filter', kOfN: { k: 2, n: 3 } },
  { name: '+ 3-of-5 pre-filter', kOfN: { k: 3, n: 5 } },
];
const CADENCES = [
  [500, 1000],
  [1000, 2000],
  [2000, 4000],
];
const temporal = [];
for (const key of jkeys) {
  for (const rule of RULES) {
    for (const [iv, piv] of rule.kOfN ? [CADENCES[0]] : CADENCES) {
      const lat = [];
      let hits = 0, runs = 0, fpHits = 0, fpRuns = 0;
      const rate = mean(pos.map(({ r }) => mean(r.jitter[key].map((s) => (s >= T ? 1 : 0)))));
      for (const { r } of pos)
        for (let seed = 1; seed <= 5; seed++) {
          runs++;
          const l = sim.phoneLatency({ phoneScores: r.jitter[key], intervalMs: iv, phoneIntervalMs: piv, durationMs: 60_000, seed, kOfN: rule.kOfN });
          if (l !== null) {
            hits++;
            lat.push(l / 1000);
          }
        }
      for (const { r } of neg)
        for (let seed = 1; seed <= 5; seed++) {
          fpRuns++;
          if (sim.phoneLatency({ phoneScores: r.jitter[key], intervalMs: iv, phoneIntervalMs: piv, durationMs: 60_000, seed, kOfN: rule.kOfN }) !== null) fpHits++;
        }
      temporal.push({ key, rule: rule.name, iv, piv, rate, hit: hits / runs, med: pct(lat, 50), p95: pct(lat, 95), fp: fpHits / fpRuns });
      out.push(`| ${key} | ${rule.name} | ${iv}/${piv} ms | ${f2(rate)} | ${f2(hits / runs)} | ${f1(pct(lat, 50))} | ${f1(pct(lat, 95))} | ${f3(fpHits / fpRuns)} |`);
    }
  }
}

// ───────────── B: presence ─────────────
out.push(`\n## B. Presence features by subset (320×240, Lite0 int8 person score)\n`);
const presSets = ['person_upper', 'face_hidden', 'pets', 'empty'].map((n) => [n, subset(n)]);
out.push('| Subset | n | face ≥ 0.6 | shoulders ≥ 0.5 | person@320 ≥ 0.5 | person@640 ≥ 0.5 | face median | shoulders median | person@320 median |');
out.push('|---|---|---|---|---|---|---|---|---|');
for (const [n, s] of presSets) {
  const r = s.map((x) => x.r.res['320']);
  const r6 = s.map((x) => x.r.res['640']);
  const frac = (a, f) => f2(a.filter(f).length / a.length);
  out.push(
    `| ${n} | ${s.length} | ${frac(r, (x) => x.face >= 0.6)} | ${frac(r, (x) => x.shoulders >= 0.5)} | ${frac(r, (x) => x.det.lite0_int8.person >= 0.5)} | ${frac(r6, (x) => x.det.lite0_int8.person >= 0.5)} | ${f2(pct(r.map((x) => x.face), 50))} | ${f2(pct(r.map((x) => x.shoulders), 50))} | ${f2(pct(r.map((x) => x.det.lite0_int8.person), 50))} |`,
  );
}

// Before/after with the REAL classifier. Observation built like production: production reducers
// (toFrameObservation) on the measured face / shoulder / person scores; object detector ran this frame.
const settings = sim.visionSettingsFromConfig(undefined, '');
const toObs = (o) => {
  const ob = {
    at: 1,
    frameQuality: 'OK',
    faceDetected: o.face > 0,
    faceScore: o.face,
    upperBodyDetected: o.shoulders >= 0.5,
    poseScore: o.shoulders,
    phoneEvaluated: true,
    phoneDetected: o.det.lite0_int8.phone >= 0.5,
    phoneScore: o.det.lite0_int8.phone,
    personScore: o.det.lite0_int8.person,
    personDetected: o.det.lite0_int8.person >= settings.personMinScore,
    inferenceMs: 0,
  };
  return ob;
};
const oldRule = (ob) => (ob.faceScore >= 0.6 || ob.upperBodyDetected ? 'PRESENT' : ob.faceScore < 0.3 ? 'ABSENT' : 'UNCERTAIN');
const cfg = (await import(pathToFileURL(join(BUILD, 'sim.mjs')).href)).DEFAULT_ENGINE_CONFIG;
const commonsPath = join(RES_DIR, 'raw-commons.json');
let commonsSets = [];
try {
  const rc = JSON.parse(readFileSync(commonsPath, 'utf8'));
  const cm = JSON.parse(readFileSync(join(HERE, 'commons-manifest.json'), 'utf8')).items.filter((i) => i.status === 'ok' && !i.exclude);
  const byc = new Map(rc.results.map((r) => [r.image.replace('/commons/', ''), r]));
  const groups = {};
  for (const i of cm) (groups[`commons:${i.situation}`] ??= []).push({ e: i, r: byc.get(i.file) });
  commonsSets = Object.entries(groups);
} catch {
  /* commons set not run */
}
const expect = { person_upper: 'PRESENT', face_hidden: 'PRESENT', pets: 'not PRESENT', empty: 'not PRESENT', phone_pos: 'PRESENT', phone_neg: 'PRESENT' };
for (const res of ['320', '640']) {
  out.push(`\n### B. Presence per frame, before (v1 rule) → after (v1.2 rule, real classifyFrame) @${res}\n`);
  out.push('Cells: PRESENT / UNCERTAIN / ABSENT counts. "Expected" is the ground truth for that subset.\n');
  out.push('| Subset | n | expected | before P/U/A | after P/U/A |');
  out.push('|---|---|---|---|---|');
  const all = [...['person_upper', 'face_hidden', 'phone_pos', 'phone_neg', 'pets', 'empty'].map((n) => [n, subset(n)]), ...commonsSets];
  for (const [n, s] of all) {
    const c0 = { PRESENT: 0, UNCERTAIN: 0, ABSENT: 0 };
    const c1 = { PRESENT: 0, UNCERTAIN: 0, ABSENT: 0 };
    for (const { r } of s) {
      const ob = toObs(r.res[res]);
      c0[oldRule(ob)]++;
      c1[sim.classifyFrame(ob, cfg)]++;
    }
    const exp = expect[n] ?? (s[0]?.e.person ? 'PRESENT' : 'not PRESENT');
    out.push(`| ${n} | ${s.length} | ${exp} | ${c0.PRESENT}/${c0.UNCERTAIN}/${c0.ABSENT} | ${c1.PRESENT}/${c1.UNCERTAIN}/${c1.ABSENT} |`);
  }
}

writeFileSync(join(RES_DIR, 'tables.md'), out.join('\n') + '\n');
writeFileSync(join(RES_DIR, 'summary.json'), JSON.stringify({ meta: raw.meta, options: optSummary, temporal }, null, 1));
console.log(out.join('\n'));
